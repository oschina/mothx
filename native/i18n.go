// This file owns the Native UI locale projection. English strings are seeded
// from the Desktop bilingual dictionary for exact shared labels, plus the
// Native-only labels below; unknown strings intentionally fall back to the
// original Chinese rather than showing a key.
var nativeLocale atomic.Value // string: "zh" or "en"

func currentLocale() string {
	if v, ok := nativeLocale.Load().(string); ok && v != "" {
		return v
	}
	return "zh"
}

func setLocale(locale string) {
	if locale == "en" {
		nativeLocale.Store("en")
		return
	}
	nativeLocale.Store("zh")
}

// setNativeLocale keeps the shell UI and the platform's own texts (menus and
// standard dialogs) on the same language.
func setNativeLocale(locale string) {
	setLocale(locale)
	if currentLocale() == "en" {
		mygo.App.SetLocale("en")
		return
	}
	mygo.App.SetLocale("zh-Hans")
}

// T translates a Native UI string. The map is intentionally keyed by the
// Chinese source text so untouched fallbacks remain readable.
func T(text string) string {
	if currentLocale() != "en" {
		return text
	}
	if translated, ok := nativeEnglish[text]; ok {
		return translated
	}
	if translated, ok := nativeEnglishExtra[text]; ok {
		return translated
	}
	// Runtime status and error messages are assembled from a fixed prefix and a
	// dynamic detail (an error string, a path, or a provider name). Translate the
	// prefix but keep the untrusted detail verbatim.
	for _, prefix := range nativeEnglishPrefixes {
		if strings.HasPrefix(text, prefix.zh) {
			// The detail is usually an untrusted error string and passes through
			// verbatim. Controlled literals (for example "尚未连接到 MothX ACP。")
			// still resolve through the dictionary; unknown details are unchanged.
			return prefix.en + T(strings.TrimPrefix(text, prefix.zh))
		}
	}
	return text
}

// Tf translates a format string and then interpolates its arguments. The
// format string is the translation key, so dynamic status messages stay in one
// dictionary instead of being assembled from hand-written English fragments.
func Tf(format string, args ...any) string {
	return fmt.Sprintf(T(format), args...)
}

// localizedError and localizedErrorf create validation errors whose fixed
// message is translated at creation time. Dynamic values stay verbatim; only
// the authored format string is localized.
func localizedError(text string) error {
	return errors.New(T(text))
}

func localizedErrorf(format string, args ...any) error {
	return fmt.Errorf(T(format), args...)
}

type nativeEnglishPrefix struct {
	zh string
	en string
}

